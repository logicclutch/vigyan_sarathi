test('quiz: a full round ends with a score', async ({ page }) => {
  await page.goto('/students/quiz')
  await page.getByRole('button', { name: /रोज़मर्रा का विज्ञान/ }).click()
  for (let i = 0; i < 8; i += 1) {
    await expect(page.getByTestId('quiz-question')).toContainText(`प्रश्न ${i + 1} / 8`)
    await page.getByTestId('quiz-question').locator('ol button').first().click()
    await page.getByRole('button', { name: i < 7 ? 'अगला प्रश्न' : 'परिणाम देखें' }).click()
  }
  await expect(page.getByTestId('quiz-result')).toContainText(/\d\s*\/8/)
  await page.getByRole('button', { name: 'फिर से खेलें' }).click()
  await expect(page.getByTestId('quiz-question')).toContainText('प्रश्न 1 / 8')
})

