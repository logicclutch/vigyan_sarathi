test('language switcher flips the whole interface, persists, and works on inner pages', async ({ page }) => {
  await page.goto('/')
  const h1 = page.locator('h1')
  await expect(h1).toContainText('जिज्ञासा से खोज तक')
  await page.getByRole('group', { name: /भाषा|language/i }).first().getByRole('button', { name: 'EN' }).click()
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await expect(h1).toContainText('From curiosity to discovery')
  await expect(page).toHaveTitle(/Vigyan Sarathi/)
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await page.goto('/teachers')
  await expect(page.locator('h1')).toHaveText('Teachers Corner')
  await page.getByRole('group', { name: /language/i }).first().getByRole('button', { name: 'हिं' }).click()
  await expect(page.locator('h1')).toHaveText('शिक्षक कॉर्नर')
  await expect(page.locator('html')).toHaveAttribute('lang', 'hi')
})

