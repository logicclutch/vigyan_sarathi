// Vectorises the organisation's raster logo (brand/logo-source.jpeg) into colour layers with potrace.
// Outputs: public/logo.svg, public/logo-mark.svg (+ dark variants), public/favicon.svg and src/components/brand/logoMeta.ts.
// The site references the SVG files with <use>, so the artwork stays out of the JavaScript bundle. Run: npm run logo
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const Jimp = require('jimp')
const potrace = require('potrace')

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = process.argv[2] ?? join(root, 'brand/logo-source.jpeg')
const TRACE_SIZE = 820 // trace at a lighter resolution: fewer nodes, still crisp for web use
const TEXT_SPLIT_Y = Math.round((678 / 1024) * TRACE_SIZE) // above: pictorial mark, below: wordmark

const PALETTE = {
  bg: [[255, 237, 202], [248, 235, 207], [240, 216, 192], [255, 248, 185], [255, 255, 255]],
  ink: [[61, 47, 25], [72, 48, 24], [48, 48, 24], [24, 0, 0], [87, 75, 49]],
  teal: [[15, 96, 104], [22, 90, 91], [24, 96, 96]],
  rust: [[182, 93, 37], [169, 93, 31], [192, 96, 48], [168, 96, 24]],
  gold: [[216, 144, 48], [222, 160, 60]],
}

const dist2 = (a, b) => (a[0] - b[0]) ** 2 + (a[1] - b[1]) ** 2 + (a[2] - b[2]) ** 2
function classify(rgb) {
  const luma = 0.299 * rgb[0] + 0.587 * rgb[1] + 0.114 * rgb[2]
  if (luma > 212) return 'bg' // anti-aliased fringe towards the cream background
  let best = 'bg'
  let bestD = Infinity
  for (const [name, swatches] of Object.entries(PALETTE)) {
    for (const sw of swatches) {
      const d = dist2(rgb, sw)
      if (d < bestD) {
        bestD = d
        best = name
      }
    }
  }
  return best
}

function trace(image, options) {
  return new Promise((resolve, reject) => {
    const tracer = new potrace.Potrace({ threshold: 128, turdSize: 28, optTolerance: 1.0, alphaMax: 1.2, optCurve: true, ...options })
    tracer.loadImage(image, (err) => {
      if (err) return reject(err)
      const tag = tracer.getPathTag()
      const d = /d="([^"]+)"/.exec(tag)?.[1] ?? ''
      resolve(d)
    })
  })
}

const round = (d) => d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n)))).replace(/\s+/g, ' ').replace(/ ?([MLCZ]) ?/g, '$1').trim()

const src = (await Jimp.read(SOURCE)).resize(TRACE_SIZE, TRACE_SIZE, Jimp.RESIZE_BICUBIC)
const { width, height } = src.bitmap
const layers = {}
const bbox = { mark: [width, height, 0, 0], text: [width, height, 0, 0] }
const names = ['ink', 'teal', 'rust', 'gold']
const bitmaps = {}
for (const name of names) {
  bitmaps[`${name}-mark`] = new Jimp(width, height, 0xffffffff)
  if (name === 'ink') bitmaps['ink-text'] = new Jimp(width, height, 0xffffffff)
}
src.scan(0, 0, width, height, function (x, y, idx) {
  const rgb = [this.bitmap.data[idx], this.bitmap.data[idx + 1], this.bitmap.data[idx + 2]]
  const cls = classify(rgb)
  if (cls === 'bg') return
  const region = y >= TEXT_SPLIT_Y ? 'text' : 'mark'
  const b = bbox[region]
  if (x < b[0]) b[0] = x
  if (y < b[1]) b[1] = y
  if (x > b[2]) b[2] = x
  if (y > b[3]) b[3] = y
  const target = region === 'text' ? (cls === 'ink' ? bitmaps['ink-text'] : null) : bitmaps[`${cls}-mark`]
  if (target) target.setPixelColor(0x000000ff, x, y)
})
for (const [key, bmp] of Object.entries(bitmaps)) {
  layers[key] = round(await trace(bmp, key === 'ink-text' ? { turdSize: 30 } : {}))
  console.log(key.padEnd(10), `${(layers[key].length / 1024).toFixed(1)} KB`)
}
const pad = 10
const markBox = [bbox.mark[0] - pad, bbox.mark[1] - pad, bbox.mark[2] - bbox.mark[0] + pad * 2, bbox.mark[3] - bbox.mark[1] + pad * 2]
const fullBox = [Math.min(bbox.mark[0], bbox.text[0]) - pad, bbox.mark[1] - pad, Math.max(bbox.mark[2], bbox.text[2]) - Math.min(bbox.mark[0], bbox.text[0]) + pad * 2, bbox.text[3] - bbox.mark[1] + pad * 2]
console.log('mark bbox', markBox, 'full bbox', fullBox)

const ts = `// Generated by scripts/trace-logo.mjs from brand/logo-source.jpeg. Do not edit by hand.
export const LOGO_MARK_VIEWBOX = '${markBox.join(' ')}'
export const LOGO_FULL_VIEWBOX = '${fullBox.join(' ')}'
/** width / height of the pictorial mark */
export const LOGO_MARK_RATIO = ${(markBox[2] / markBox[3]).toFixed(4)}
`
writeFileSync(join(root, 'src/components/brand/logoMeta.ts'), ts)

const COLORS = { ink: '#3d2f19', teal: '#176b74', rust: '#b85d25', gold: '#d8a030' }
const svg = (viewBox, withText) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" role="img" aria-label="विज्ञान सारथी">
  <g id="${withText ? 'full' : 'mark'}" fill-rule="evenodd">
    <path fill="var(--logo-rust, ${COLORS.rust})" d="${layers['rust-mark']}"/>
    <path fill="var(--logo-gold, ${COLORS.gold})" d="${layers['gold-mark']}"/>
    <path fill="var(--logo-teal, ${COLORS.teal})" d="${layers['teal-mark']}"/>
    <path fill="var(--logo-ink, ${COLORS.ink})" d="${layers['ink-mark']}"/>
${withText ? `\n    <path fill="var(--logo-ink, ${COLORS.ink})" d="${layers['ink-text']}"/>` : ''}
  </g>
</svg>
`
writeFileSync(join(root, 'public/logo.svg'), svg(fullBox.join(' '), true))
writeFileSync(join(root, 'public/logo-mark.svg'), svg(markBox.join(' '), false))
const DARK = { ink: '#f3e9d2', teal: '#5fc0cf', rust: '#ee8a4a', gold: '#f5c04a' }
const darkSvg = (viewBox, withText) => svg(viewBox, withText).replace(/var\(--logo-(\w+), #[0-9a-f]{6}\)/g, (_, k) => `var(--logo-${k}, ${DARK[k]})`)
writeFileSync(join(root, 'public/logo-mark-dark.svg'), darkSvg(markBox.join(' '), false))
writeFileSync(join(root, 'public/logo-dark.svg'), darkSvg(fullBox.join(' '), true))
const [fx, fy, fw, fh] = markBox
const side = Math.max(fw, fh) * 1.12
const ox = fx - (side - fw) / 2
const oy = fy - (side - fh) / 2
const favicon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${ox} ${oy} ${side} ${side}">
  <rect x="${ox}" y="${oy}" width="${side}" height="${side}" rx="${side * 0.2}" fill="#fdefd0"/>
  <g fill-rule="evenodd">
    <path fill="${COLORS.rust}" d="${layers['rust-mark']}"/>
    <path fill="${COLORS.gold}" d="${layers['gold-mark']}"/>
    <path fill="${COLORS.teal}" d="${layers['teal-mark']}"/>
    <path fill="${COLORS.ink}" d="${layers['ink-mark']}"/>
  </g>
</svg>
`
writeFileSync(join(root, 'public/favicon.svg'), favicon)
const total = Object.values(layers).reduce((n, d) => n + d.length, 0)
console.log(`total path data ${(total / 1024).toFixed(1)} KB; wrote logoMeta.ts, public/logo(.svg|-dark.svg), public/logo-mark(.svg|-dark.svg), public/favicon.svg`)
